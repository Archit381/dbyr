"""Count Intent fields by derivation route (x-route annotations in the schema).

R2 fields have a counterpart in an existing obligation (SB 53, RAISE, EU Code of
Practice, FRONTIER Act as introduced) under the authors' mapping in paper
Appendix B. The mapping has not been checked against regulators' templates, so
the count is an upper bound on overlap, not a burden measurement.

    python -m dbyr.routes [--tex-dir ../generated]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from .schemas import load_schema

META = {"schema_version", "record_type", "filed_at", "signer", "amends"}


def substantive_fields(required_only: bool = True) -> dict[str, list[str]]:
    s = load_schema("training_run_intent.schema.json")
    names = s["required"] + ["run_kind"] if required_only else list(s["properties"])
    return {n: s["properties"][n].get("x-route", []) for n in names if n not in META}


def counts() -> dict:
    f = substantive_fields()
    return {
        "n": len(f),
        "with_r2": sorted(n for n, r in f.items() if "R2" in r),
        "r1_only": sorted(n for n, r in f.items() if r == ["R1"]),
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tex-dir", type=Path)
    a = ap.parse_args(argv)
    c = counts()
    print(f"{len(c['with_r2'])} of {c['n']} substantive Intent fields have an R2 counterpart: {', '.join(c['with_r2'])}")
    print(f"{len(c['r1_only'])} are R1 only (new content): {', '.join(c['r1_only'])}")
    if a.tex_dir:
        fld = lambda n: r"\fld{" + n.replace("_", r"\_") + "}"
        a.tex_dir.mkdir(parents=True, exist_ok=True)
        (a.tex_dir / "routes_macros.tex").write_text(
            "% Generated by code/dbyr/routes.py. Do not edit by hand.\n"
            f"\\newcommand{{\\rtN}}{{{c['n']}}}\n\\newcommand{{\\rtRTwo}}{{{len(c['with_r2'])}}}\n"
            f"\\newcommand{{\\rtROneOnly}}{{{len(c['r1_only'])}}}\n"
            f"\\newcommand{{\\rtROneOnlyList}}{{{', '.join(map(fld, c['r1_only']))}}}\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
