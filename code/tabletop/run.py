"""Run the tabletop exercise.

    python -m tabletop.run [--tex-dir ../generated]

Round 1 scores every evasion against the v0.1 rule set ("baseline"). Round 2
scores the same evasions against v0.1 plus the adequacy checks (now v0.3), which share
their sources with the evasions (round 2 is in-sample; see attacks.py). An
evasion is "caught" if any check returns an
error (the filing cannot be lodged) or a conduct finding (it lodges, but the
breach is surfaced for adjudication) on the modified filing set. Honest filing sets must return no errors under
either profile; any error there is a false positive and is reported.
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from dbyr.check import check_set  # noqa: E402
from tabletop.attacks import ATTACKS  # noqa: E402
from tabletop.scenarios import SCENARIOS  # noqa: E402


def findings(filings: dict, profile: str) -> list:
    return check_set(filings, profile=profile)


def error_codes(found: list) -> list[str]:
    """Codes that count as a catch: lodging errors and surfaced breaches."""
    return sorted({f.code for _, f in found if f.severity in ("error", "conduct")})


def leaf_count(value) -> int:
    if isinstance(value, dict):
        return sum(leaf_count(v) for v in value.values())
    if isinstance(value, list):
        return sum(leaf_count(v) for v in value) if value else 1
    return 1


def run() -> dict:
    controls = {}
    for sid, build in SCENARIOS.items():
        honest = build()
        controls[sid] = {
            p: {"errors": error_codes(findings(honest, p)),
                "warnings": sorted({f.code for _, f in findings(honest, p) if f.severity == "warning"})}
            for p in ("baseline", "adequacy")
        }
        controls[sid]["intent_leaves"] = leaf_count(honest["intent:A"])
        controls[sid]["closeout_leaves"] = leaf_count(honest["closeout:A"])

    rows = []
    for a in ATTACKS:
        filings = SCENARIOS[a.scenario]()
        a.apply(filings)
        r1, r2 = error_codes(findings(filings, "baseline")), error_codes(findings(filings, "adequacy"))
        rows.append({"id": a.id, "scenario": a.scenario, "title": a.title, "source": a.source,
                     "conceals": a.conceals, "catch": a.catch,
                     "round1_caught": bool(r1), "round1_codes": r1,
                     "round2_caught": bool(r2), "round2_codes": r2})

    n = len(rows)
    residual = [r for r in rows if not r["round2_caught"]]
    unexplained = [r["id"] for r in residual if not r["catch"]]
    return {
        "n_attacks": n,
        "round1_caught": sum(r["round1_caught"] for r in rows),
        "round2_caught": sum(r["round2_caught"] for r in rows),
        "residual": [r["id"] for r in residual],
        "residual_without_account": unexplained,
        "false_positives": {sid: c["adequacy"]["errors"] + c["baseline"]["errors"] for sid, c in controls.items()
                            if c["adequacy"]["errors"] or c["baseline"]["errors"]},
        "by_source": {s: {"n": sum(r["source"] == s for r in rows),
                          "round2_caught": sum(r["source"] == s and r["round2_caught"] for r in rows)}
                      for s in sorted({r["source"] for r in rows})},
        "controls": controls,
        "rows": rows,
    }


# ---------------------------------------------------------------- output

def _tex(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def latex(result: dict) -> str:
    mark = lambda b: r"\textbf{caught}" if b else "missed"
    lines = []
    for r in result["rows"]:
        what = "" if r["round2_caught"] else _tex(r["catch"])
        lines.append(f"{r['id']} & {_tex(r['title'])} & {_tex(r['source'])} & {mark(r['round1_caught'])} & "
                     f"{mark(r['round2_caught'])} & {what} \\\\ \\addlinespace")
    rows = "\n".join(lines) + "\n"
    s = result["controls"]
    m = {
        "ttN": result["n_attacks"],
        "ttRoundOne": result["round1_caught"],
        "ttRoundTwo": result["round2_caught"],
        "ttResidual": len(result["residual"]),
        "ttResidualIds": ", ".join(result["residual"]),
        "ttFalsePositives": sum(len(v) for v in result["false_positives"].values()),
        "ttScenarios": len(s),
        "ttIntentLeavesMin": min(c["intent_leaves"] for c in s.values()),
        "ttIntentLeavesMax": max(c["intent_leaves"] for c in s.values()),
        "ttExternalN": sum(v["n"] for k, v in result["by_source"].items() if k in ("External review", "Earlier critique")),
    }
    head = "% Generated by code/tabletop/run.py. Do not edit by hand.\n"
    return (head + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items())
            + "\\newcommand{\\ttRows}{%\n" + rows + "}\n")


def markdown(result: dict) -> str:
    out = ["# Tabletop exercise", "",
           f"Evasions: {result['n_attacks']}. Caught by v0.1 rules: {result['round1_caught']}. "
           f"Caught under current adequacy rules (v0.3): {result['round2_caught']}. Residual: {', '.join(result['residual'])}.",
           f"False positives on honest filings: {result['false_positives'] or 'none'}.", "",
           "| ID | Scen. | Evasion | Source | v0.1 | v0.3 | v0.3 codes | If missed, what exposes it |",
           "|---|---|---|---|---|---|---|---|"]
    for r in result["rows"]:
        out.append(f"| {r['id']} | {r['scenario']} | {r['title']} | {r['source']} | "
                   f"{'caught' if r['round1_caught'] else 'missed'} | {'caught' if r['round2_caught'] else 'missed'} | "
                   f"{', '.join(r['round2_codes'])} | {r['catch'] if not r['round2_caught'] else ''} |")
    out += ["", "## Honest filing controls", ""]
    for sid, c in result["controls"].items():
        out.append(f"- {sid}: baseline errors {c['baseline']['errors'] or 'none'}, adequacy errors "
                   f"{c['adequacy']['errors'] or 'none'}; warnings {c['adequacy']['warnings'] or 'none'}; "
                   f"Intent has {c['intent_leaves']} filled values")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tex-dir", type=Path)
    args = ap.parse_args(argv)
    result = run()
    here = Path(__file__).parent
    (here / "results.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    report = markdown(result)
    (here / "results.md").write_text(report, encoding="utf-8")
    print(report)
    if args.tex_dir:
        args.tex_dir.mkdir(parents=True, exist_ok=True)
        (args.tex_dir / "tabletop_macros.tex").write_text(latex(result), encoding="utf-8")
    if result["false_positives"]:
        print("FALSE POSITIVES ON HONEST FILINGS:", result["false_positives"])
        return 1
    if result["residual_without_account"]:
        print("Residual evasions with no stated account:", result["residual_without_account"])
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
